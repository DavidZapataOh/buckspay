#[cfg(test)]
mod tests {
    use super::*;
    use core::str::FromStr;
    use solana_hash::Hash;

    #[test]
    fn genesis_hashes_match_the_clusters() {
        let decode = |base58| Hash::from_str(base58).unwrap().to_bytes();
        assert_eq!(
            decode("5eykt4UsFv8P8NJdTREpY1vzqKqZKvdpKuc147dw2N9d"),
            MAINNET_GENESIS_HASH
        );
        assert_eq!(
            decode("EtWTRABZaYq6iMfeYKouRu166VU2xqa1wcaWoxPkrZBG"),
            DEVNET_GENESIS_HASH
        );
    }
}
