//! The reward pool: its configuration, the per-mint policy, and the incremental Merkle tree whose
//! leaves the program itself computes from settled delivery words.
use anchor_lang::prelude::*;
use buckspay_protocol::payword::MAX_LEAVES_PER_TX;
use buckspay_zk_verify::fr;
use solana_poseidon::{hashv, Endianness, Parameters};

use crate::error::BuckspayError;

pub const REWARD_CONFIG_SEED: &[u8] = b"reward-config";
pub const REWARD_MINT_SEED: &[u8] = b"reward-mint";
pub const REWARD_TREE_SEED: &[u8] = b"reward-tree";
/// The first byte of the key of a reward pool's ledger; a lock's ledger carries a compressed
/// P-256 point (`0x02` or `0x03`) and an attester's ledger `ATTESTER_LEDGER_MARKER`.
pub const REWARD_LEDGER_MARKER: u8 = 0xfe;
pub const TREE_DEPTH: usize = 20;
pub const TREE_CAPACITY: u32 = 1 << TREE_DEPTH;
/// One root is pushed per transaction, so flushing the ring takes this many paid transactions.
pub const ROOT_HISTORY: usize = 256;

#[account]
#[derive(InitSpace)]
pub struct RewardConfig {
    pub admin: Pubkey,
    pub pauser: Pubkey,
    /// Stops claims only: settling delivery words is never paused.
    pub paused: bool,
    pub bump: u8,
}

/// What a mint pays for a delivery word. `word_value`, `word_fee`, `unit` and `max_fee` are fixed
/// when the mint is configured: a signed commitment is never re-priced.
#[account]
#[derive(InitSpace)]
pub struct RewardMint {
    pub mint: Pubkey,
    pub word_value: u64,
    pub word_fee: u64,
    pub unit: u64,
    pub max_fee: u64,
    pub claim_fee: u64,
    pub fee_account: Pubkey,
    pub claim_cap: u64,
    pub epoch: u32,
    pub bump: u8,
}

#[derive(AnchorSerialize, AnchorDeserialize, Clone, Copy, Debug)]
pub struct RewardPolicy {
    pub word_value: u64,
    pub word_fee: u64,
    pub max_fee: u64,
    pub claim_fee: u64,
    pub fee_account: Pubkey,
    pub claim_cap: u64,
}

#[account(zero_copy)]
pub struct RewardTree {
    pub mint: Pubkey,
    pub epoch: u32,
    pub next_index: u32,
    pub root_index: u32,
    pub bump: u8,
    pub padding: [u8; 3],
    pub filled: [[u8; 32]; TREE_DEPTH],
    pub roots: [[u8; 32]; ROOT_HISTORY],
}

#[event]
pub struct LeafAppended {
    pub epoch: u32,
    pub index: u32,
    pub leaf: [u8; 32],
    pub exp: u8,
}

