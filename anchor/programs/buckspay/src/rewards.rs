pub mod tree {
    use super::*;

    fn hash2(left: &[u8; 32], right: &[u8; 32]) -> Result<[u8; 32]> {
        hashv(
            Parameters::Bn254X5,
            Endianness::BigEndian,
            &[&left[..], &right[..]],
        )
        .map(|hash| hash.to_bytes())
        .map_err(|_| error!(BuckspayError::HashFailed))
    }

    /// The leaf of a word batch: `Poseidon(inner, exp)` with `exp` as a 32-byte big-endian
    /// integer. Both inputs are 32 bytes, so the syscall's padded path takes them.
    pub fn leaf(inner: &[u8; 32], exp: u8) -> Result<[u8; 32]> {
        require!(fr::is_canonical(inner), BuckspayError::NonCanonicalInner);
        let mut exp32 = [0u8; 32];
        exp32[31] = exp;
        hash2(inner, &exp32)
    }

    /// Appends `leaves` and pushes the one root they leave into the ring. Returns the index of the
    /// first leaf. Only the last leaf walks to the top: an earlier one stops at the first level
    /// where it is a left child, which is the only place a later leaf reads what it left behind.
    pub fn append_batch(tree: &mut RewardTree, leaves: &[[u8; 32]]) -> Result<u32> {
        require!(
            !leaves.is_empty() && leaves.len() <= MAX_LEAVES_PER_TX,
            BuckspayError::InnersDoNotMatchWords
        );
        require!(
            tree.next_index <= TREE_CAPACITY - MAX_LEAVES_PER_TX as u32,
            BuckspayError::TreeFull
        );
        let first = tree.next_index;
        let mut root = [0u8; 32];
        for (i, leaf) in leaves.iter().enumerate() {
            let last = i + 1 == leaves.len();
            let mut at = tree.next_index;
            let mut current = *leaf;
            for (level, zero) in ZEROS.iter().enumerate() {
                if at & 1 == 0 {
                    tree.filled[level] = current;
                    if !last {
                        break;
                    }
                    current = hash2(&current, zero)?;
                } else {
                    current = hash2(&tree.filled[level], &current)?;
                }
                at >>= 1;
            }
            root = current;
            tree.next_index = tree
                .next_index
                .checked_add(1)
                .ok_or_else(|| error!(BuckspayError::TreeFull))?;
        }
        let slot = tree.root_index as usize % ROOT_HISTORY;
        tree.roots[slot] = root;
        tree.root_index = tree
            .root_index
            .checked_add(1)
            .ok_or_else(|| error!(BuckspayError::TreeFull))?;
        Ok(first)
    }

    /// Whether `root` is one of the roots the tree pushed. The unfilled entries of the ring are
    /// all zero, and a zero root never matches them.
    pub fn known_root(tree: &RewardTree, root: &[u8; 32]) -> bool {
        *root != [0u8; 32] && tree.roots.iter().any(|known| known == root)
    }
}
